CREATE TABLE IF NOT EXISTS `qixi_crm_b_seckill_activity_stat_people` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT,
  `activity_id` bigint unsigned NOT NULL,
  `uid` bigint unsigned NOT NULL DEFAULT 0,
  `nickname` varchar(64) NOT NULL DEFAULT '',
  `phone` varchar(32) NOT NULL DEFAULT '',
  `mer_id` bigint unsigned NOT NULL DEFAULT 0,
  `sum_total_num` int NOT NULL DEFAULT 0,
  `order_count` int NOT NULL DEFAULT 0,
  `sum_pay_price` decimal(12,2) NOT NULL DEFAULT 0,
  `last_join_time` datetime NOT NULL,
  PRIMARY KEY (`id`),
  KEY `idx_activity` (`activity_id`),
  KEY `idx_uid` (`uid`),
  KEY `idx_mer` (`mer_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS `qixi_crm_b_seckill_activity_stat_order` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT,
  `activity_id` bigint unsigned NOT NULL,
  `order_sn` varchar(64) NOT NULL DEFAULT '',
  `uid` bigint unsigned NOT NULL DEFAULT 0,
  `nickname` varchar(64) NOT NULL DEFAULT '',
  `mer_id` bigint unsigned NOT NULL DEFAULT 0,
  `status` tinyint NOT NULL DEFAULT 0 COMMENT '1待付款 2待发货 3待收货 4待评价 5完成 6已退款 8待核销',
  `status_text` varchar(32) NOT NULL DEFAULT '',
  `pay_price` decimal(12,2) NOT NULL DEFAULT 0,
  `total_num` int NOT NULL DEFAULT 0,
  `paid` tinyint NOT NULL DEFAULT 0,
  `create_time` datetime NOT NULL,
  `pay_time` datetime DEFAULT NULL,
  PRIMARY KEY (`id`),
  KEY `idx_activity` (`activity_id`),
  KEY `idx_status` (`status`),
  KEY `idx_mer` (`mer_id`),
  KEY `idx_order_sn` (`order_sn`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

